#!/usr/bin/env python3
"""Builds js/worldland.js (coastlines for the passport's world and Europe stamp maps) from Natural Earth 110m land (public domain).
Usage: python3 tools/world_land.py /path/to/ne_110m_land.json   (download: https://github.com/martynafford/natural-earth-geojson, 110m/physical/ne_110m_land.json)
Drops Antarctica and tiny islands, simplifies (Douglas-Peucker 0.3 degrees), one decimal. Output: const PP_WORLD=[ [[lon,lat],...], ... ]."""
import json, sys, math
def dp(pts, tol):
    if len(pts) < 3: return pts
    a, b = pts[0], pts[-1]; dx, dy = b[0]-a[0], b[1]-a[1]; n = math.hypot(dx, dy) or 1e-9
    i, m = max(((i, abs(dy*(p[0]-a[0]) - dx*(p[1]-a[1]))/n) for i, p in enumerate(pts[1:-1], 1)), key=lambda t: t[1])
    return dp(pts[:i+1], tol)[:-1] + dp(pts[i:], tol) if m > tol else [a, b]
d = json.load(open(sys.argv[1])); rings = []
for f in d["features"]:
    g = f["geometry"]; polys = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
    for p in polys:
        r = p[0]; la = [q[1] for q in r]; lo = [q[0] for q in r]
        if max(la) < -60 or (max(lo)-min(lo) < 1.2 and max(la)-min(la) < 1.2): continue
        h = len(r)//2; s = dp(r[:h+1], 0.3)[:-1] + dp(r[h:], 0.3)
        if len(s) >= 4: rings.append([[round(x, 1), round(y, 1)] for x, y in s])
open("js/worldland.js", "w").write("/* generated by tools/world_land.py from Natural Earth 110m land (public domain) */\nconst PP_WORLD=" + json.dumps(rings, separators=(",", ":")) + ";\n")
print(len(rings), "rings", sum(len(r) for r in rings), "points")
